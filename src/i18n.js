// Picks the language: an explicit choice wins, then whichever of English or French comes
// first in the device's language list.
export function pickLang({ param, saved, languages = [] } = {}) {
  for (const v of [param, saved]) if (LANGS.includes(v)) return v;
  const first = languages.map(String).find((l) => /^(en|fr)\b/i.test(l));
  return first && /^fr/i.test(first) ? 'fr' : 'en';
}

const plurals = {};
const numbers = {};
export function fmtNumber(n, lang = 'en', opts) {
  const key = `${lang}${JSON.stringify(opts ?? {})}`;
  numbers[key] ??= new Intl.NumberFormat(LOCALE[lang] ?? LOCALE.en, opts);
  return numbers[key].format(n);
}

// The message for a key in a language, with {placeholders} filled in. Numbers are formatted
// for the locale, and { one, other } messages are picked by the count in params.n.
export function t(lang, key, params = {}) {
  let m = MESSAGES[lang]?.[key] ?? MESSAGES.en[key];
  if (m === undefined) return key;
  if (typeof m === 'object') {
    plurals[lang] ??= new Intl.PluralRules(LOCALE[lang] ?? LOCALE.en);
    m = m[plurals[lang].select(Number(params.n ?? 0))] ?? m.other;
  }
  return m.replace(/\{(\w+)\}/g, (whole, k) => {
    const v = params[k];
    if (v === undefined) return whole;
    return typeof v === 'number' ? fmtNumber(v, lang) : String(v);
  });
}

const MONTHS = {
  en: ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'],
  fr: ['janv.', 'févr.', 'mars', 'avr.', 'mai', 'juin', 'juil.', 'août', 'sept.', 'oct.', 'nov.', 'déc.'],
};

// "15 Oct 2026" or "15 oct. 2026" (and "1er" for the first in French). Anything that isn't
// a YYYY-MM-DD date is returned as it is.
export function fmtDate(iso, lang = 'en') {
  const [y, m, d] = String(iso ?? '').split('-').map(Number);
  if (!(y && m >= 1 && m <= 12 && d)) return String(iso ?? '');
  const day = lang === 'fr' && d === 1 ? '1er' : String(d);
  return `${day} ${(MONTHS[lang] ?? MONTHS.en)[m - 1]} ${y}`;
}
export function fmtMonthYear(iso, lang = 'en') {
  const [y, m] = String(iso ?? '').split('-').map(Number);
  return m >= 1 && m <= 12 ? `${(MONTHS[lang] ?? MONTHS.en)[m - 1]} ${y}` : String(iso ?? '');
}

// "70,000 km" or "70 000 km"; the French space can't break.
export function fmtDistance(value, unit, lang = 'en') {
  return `${fmtNumber(Math.round(value), lang)}${lang === 'fr' ? N : ' '}${unit}`;
}

// An advertised price in whole dollars of the listing's own currency: "$49,315" or "US$12,000",
// "49 315 $" or "12 000 $ US".
export function fmtPrice(amount, currency = 'CAD', lang = 'en') {
  return fmtNumber(amount, lang, { style: 'currency', currency, minimumFractionDigits: 0, maximumFractionDigits: 0 });
}

// Canadian dollars: "$89.99" or "89,99 $".
export function fmtMoney(cents, lang = 'en') {
  if (lang === 'fr') return fmtNumber(cents / 100, 'fr', { style: 'currency', currency: 'CAD' });
  return `$${fmtNumber(cents / 100, 'en', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
}
